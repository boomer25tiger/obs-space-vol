"""S06R Phases 2 and 3: OHLC panel rebuild, and the CME calendar exclusion.

Phase 2 rebuilds the panels from the S04 repaired bars carrying open, high,
low and close, persists the `present` mask alongside (absent in S05), and
rebuilds M6_PARK / M6_GK from true bar high and low.

Padding rule for a minute with no bar: O = H = L = C = the forward-filled
close, which is the only assignment consistent with "no trade occurred".
The close grid is built by the same ffill/bfill as S03 analysis.py:41 so it
is comparable byte-for-byte with the stored panels.

Phase 3 builds the non-trading exclusion from the CME equity-index holiday
calendar by RULE, with no reference to any realized quantity (item 42).
"""
import json, os, sys, time
import numpy as np, pandas as pd
BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.dirname(os.path.dirname(BASE))
RES, CACHE = os.path.join(BASE, "results"), os.path.join(BASE, "cache")
S04 = os.path.join(ROOT, "sessions", "s04-repairs-diagnostics", "results")
S05 = os.path.join(ROOT, "sessions", "s05-reliability-mcs", "results")
S05B = os.path.join(ROOT, "sessions", "s05b-defect-and-estimator-audit", "results")
sys.path.insert(0, os.path.join(BASE, "tests"))
from test_invariants import assert_range_inputs, InvariantViolation
N_GRID = {"RTH": 390, "GLOBEX": 1380}
OFF = {"RTH": 570, "GLOBEX": 1080}
timers, out = {}, {}

def build_ohlc(df, root, geom):
    sub = df[df["root"] == root]
    n = N_GRID[geom]
    if geom == "RTH":
        sub = sub[(sub["ny_min"] >= 570) & (sub["ny_min"] < 960)]
        slot = sub["ny_min"] - 570
    else:
        slot = (sub["ny_min"] - 1080) % 1440
        ok = slot < 1380
        sub, slot = sub[ok], slot[ok]
    dates = np.sort(sub["tdate"].unique())
    didx = {d: i for i, d in enumerate(dates)}
    S = len(dates)
    ri = sub["tdate"].map(didx).values
    ci = slot.values
    grids = {}
    for col in ["open", "high", "low", "close"]:
        g = np.full((S, n), np.nan)
        g[ri, ci] = np.log(sub[col].values / 1e9)
        grids[col] = g
    present = ~np.isnan(grids["close"])
    close = pd.DataFrame(grids["close"]).ffill(axis=1).bfill(axis=1).values
    for col in ["open", "high", "low"]:
        grids[col] = np.where(present, grids[col], close)
    grids["close"] = close
    return dates, grids, present

def easter(y):
    """Anonymous Gregorian algorithm."""
    a=y%19; b=y//100; c=y%100; d=b//4; e=b%4; f=(b+8)//25; g=(b-f+1)//3
    h=(19*a+b-d-g+15)%30; i=c//4; k=c%4; l=(32+2*e+2*i-h-k)%7
    m=(a+11*h+22*l)//451; mo=(h+l-7*m+114)//31; da=((h+l-7*m+114)%31)+1
    return pd.Timestamp(y, mo, da)

def cme_holidays(years):
    """CME equity-index non-trading sessions, generated by calendar RULE
    from the CME Group published holiday calendar (no data touched).

    Two classes:
      EARLY_CLOSE_1300 - day session halts 13:00 ET: MLK, Presidents,
        Memorial, Independence, Labor, Thanksgiving, and Juneteenth from
        2022, the first year CME observed it after it became a federal
        holiday in June 2021.
      FULL_CLOSURE_0930 - the day session does not open: Good Friday, and
        2018-12-05, the National Day of Mourning for George H. W. Bush,
        which was announced on 2018-12-01 and is therefore ex-ante
        determinable in the sense item 42 requires.
    """
    rows = []
    for y in years:
        gf = easter(y) - pd.Timedelta(days=2)
        rows.append(dict(date=str(gf.date()), holiday="GoodFriday",
                         halt_ny="09:30", halt_ny_min=570,
                         cls="FULL_CLOSURE_0930"))
        if y >= 2022:
            j = pd.Timestamp(y, 6, 19)
            if j.dayofweek == 5: j = pd.Timestamp(y, 6, 20)
            elif j.dayofweek == 6: j = pd.Timestamp(y, 6, 20)
            rows.append(dict(date=str(j.date()), holiday="Juneteenth",
                             halt_ny="13:00", halt_ny_min=780,
                             cls="EARLY_CLOSE_1300"))
        if y == 2018:
            rows.append(dict(date="2018-12-05", holiday="DayOfMourning",
                             halt_ny="09:30", halt_ny_min=570,
                             cls="FULL_CLOSURE_0930"))
        def nth_dow(month, dow, n):
            d = pd.Timestamp(y, month, 1)
            off = (dow - d.dayofweek) % 7
            return d + pd.Timedelta(days=off + 7 * (n - 1))
        def last_dow(month, dow):
            d = pd.Timestamp(y, month, 1) + pd.offsets.MonthEnd(0)
            return d - pd.Timedelta(days=(d.dayofweek - dow) % 7)
        jul4 = pd.Timestamp(y, 7, 4)
        if jul4.dayofweek == 5: jul4 = pd.Timestamp(y, 7, 3)
        elif jul4.dayofweek == 6: jul4 = pd.Timestamp(y, 7, 5)
        for name, d in [("MLK", nth_dow(1, 0, 3)), ("Presidents", nth_dow(2, 0, 3)),
                        ("Memorial", last_dow(5, 0)), ("Independence", jul4),
                        ("Labor", nth_dow(9, 0, 1)), ("Thanksgiving", nth_dow(11, 3, 4))]:
            rows.append(dict(date=str(d.date()), holiday=name, halt_ny="13:00",
                             halt_ny_min=780, cls="EARLY_CLOSE_1300"))
    return pd.DataFrame(rows).sort_values("date").reset_index(drop=True)

def main():
    t0 = time.time(); t = time.time()
    # ---------------- Phase 2
    cmp_rows, hl_rows, m6_rows = [], [], []
    PANELS = {}
    for geom in ["GLOBEX", "RTH"]:
        df = pd.read_parquet(os.path.join(S04, f"bars_{geom}.parquet"))
        for root in ["ES", "NQ"]:
            dates, grids, present = build_ohlc(df, root, geom)
            assert_range_inputs(grids, f"{root}/{geom}")
            np.savez_compressed(os.path.join(CACHE, f"panel_ohlc_{root}_{geom}.npz"),
                dates=dates.astype("datetime64[D]").astype(str), present=present,
                **{k: v.astype(np.float32) for k, v in grids.items()})
            PANELS[(root, geom)] = (dates, grids, present)
            old = np.load(os.path.join(S05, f"panel_{root}_{geom}_B0.npz"))["logpx"]
            new = grids["close"].astype(np.float32)
            same = bool(np.array_equal(old, new))
            nd = int((old != new).sum())
            cmp_rows.append(dict(root=root, geom=geom, shape=str(new.shape),
                byte_identical=same, n_differing=nd,
                max_abs_diff=float(np.abs(old.astype(np.float64)-new.astype(np.float64)).max())))
            sub = df[df["root"] == root].copy()
            sub["year"] = pd.DatetimeIndex(sub["tdate"]).year
            hl = sub.groupby("year").apply(
                lambda g: pd.Series(dict(n_bars=len(g),
                    n_high_eq_low=int((g["high"] == g["low"]).sum()),
                    share_high_eq_low=float((g["high"] == g["low"]).mean()))),
                include_groups=False).reset_index()
            hl["root"], hl["geom"] = root, geom
            hl_rows.append(hl)
    pd.DataFrame(cmp_rows).to_csv(os.path.join(RES, "phase2_close_grid_check.csv"), index=False)
    pd.concat(hl_rows).to_csv(os.path.join(RES, "phase2_high_eq_low.csv"), index=False)
    timers["phase2_build"] = round(time.time()-t, 1)
    out["phase2_close_identical"] = bool(all(r["byte_identical"] for r in cmp_rows))

    # ---- M6 old vs new, at the 1day window (the S05 construction)
    t = time.time()
    for (root, geom), (dates, grids, present) in PANELS.items():
        cl, hi, lo, op = grids["close"], grids["high"], grids["low"], grids["open"]
        r1 = np.diff(cl, axis=1)
        cum = np.cumsum(r1, axis=1)
        o_hi = np.maximum(cum.max(axis=1), 0.0); o_lo = np.minimum(cum.min(axis=1), 0.0)
        o_cl = cum[:, -1]
        old_park = (o_hi - o_lo) ** 2 / (4 * np.log(2))
        old_gk = 0.5 * (o_hi - o_lo) ** 2 - (2 * np.log(2) - 1) * o_cl ** 2
        n_hi = hi.max(axis=1); n_lo = lo.min(axis=1)
        n_op = op[:, 0]; n_cl = cl[:, -1]
        new_park = (n_hi - n_lo) ** 2 / (4 * np.log(2))
        new_gk = 0.5 * (n_hi - n_lo) ** 2 - (2*np.log(2)-1) * (n_cl - n_op) ** 2
        np.savez_compressed(os.path.join(CACHE, f"m6_{root}_{geom}.npz"),
            park_new=new_park, gk_new=new_gk, park_old=old_park, gk_old=np.maximum(old_gk,1e-300))
        for nm, o, nw in [("M6_PARK", old_park, new_park), ("M6_GK", np.maximum(old_gk,1e-300), new_gk)]:
            m6_rows.append(dict(root=root, geom=geom, model=nm,
                mean_old=float(o.mean()), mean_new=float(nw.mean()),
                ratio_new_over_old=float(nw.mean()/o.mean()),
                n_zero_old=int((o<=1e-300).sum()), n_zero_new=int((nw<=0).sum()),
                n_windows=int(len(o))))
    pd.DataFrame(m6_rows).to_csv(os.path.join(RES, "phase2_m6_old_vs_new.csv"), index=False)
    timers["phase2_m6"] = round(time.time()-t, 1)

    # ---- E3 gate on corrected series (proxy errors vs a noise-robust reference)
    t = time.time()
    e3 = []
    for (root, geom), (dates, grids, present) in PANELS.items():
        z6 = np.load(os.path.join(CACHE, f"m6_{root}_{geom}.npz"))
        cl = grids["close"]; r1 = np.diff(cl, axis=1)
        M = r1.shape[1]
        rv = (r1**2).sum(axis=1)
        a = np.abs(r1)
        bv = (np.pi/2)*(M/(M-1))*(a[:,1:]*a[:,:-1]).sum(axis=1)
        ref = np.load(os.path.join(S05B, "cache", f"ref_{root}_{geom}_B0.npz"))["kernel"]
        n = min(len(ref), len(rv))
        series = {"RV": rv[:n], "BV": bv[:n], "PARK": z6["park_new"][:n],
                  "GK": z6["gk_new"][:n], "PARK_old": z6["park_old"][:n],
                  "GK_old": z6["gk_old"][:n]}
        pos = (ref[:n] > 0)
        for k, v in series.items(): pos &= (v > 0)
        lref = np.log(ref[:n][pos])
        err = {k: np.log(v[pos]) - lref for k, v in series.items()}
        names = list(err)
        C = np.corrcoef(np.vstack([err[k] for k in names]))
        for i, ni in enumerate(names):
            for j, nj in enumerate(names):
                if j <= i: continue
                e3.append(dict(root=root, geom=geom, proxy_i=ni, proxy_j=nj,
                               error_corr=float(C[i, j]), n=int(pos.sum())))
    E3 = pd.DataFrame(e3)
    E3.to_csv(os.path.join(RES, "phase2_e3_gate.csv"), index=False)
    pg_new = E3[(E3.proxy_i=="PARK")&(E3.proxy_j=="GK")]
    pg_old = E3[(E3.proxy_i=="PARK_old")&(E3.proxy_j=="GK_old")]
    out["e3_park_gk_corr_new"] = float(pg_new.error_corr.mean())
    out["e3_park_gk_corr_old"] = float(pg_old.error_corr.mean())
    out["e3_max_offdiag_new"] = float(E3[~E3.proxy_i.str.contains("_old") &
                                         ~E3.proxy_j.str.contains("_old")].error_corr.abs().max())
    out["e3_excluded_at_0p20"] = bool(out["e3_max_offdiag_new"] > 0.20)
    timers["phase2_e3"] = round(time.time()-t, 1)

    # ---------------- Phase 3, calendar exclusion
    t = time.time()
    years = range(2016, 2024)
    H = cme_holidays(years)
    H.to_csv(os.path.join(RES, "phase3_calendar.csv"), index=False)
    excl = {}
    exc_rows = []
    halt_of = dict(zip(H.date, H.halt_ny_min))
    hol = set(H.date)
    for (root, geom), (dates, grids, present) in PANELS.items():
        n = N_GRID[geom]
        ds = np.array([str(d)[:10] for d in dates.astype("datetime64[D]")])
        is_hol = np.isin(ds, list(hol))
        tradeable = np.ones((len(ds), n), bool)
        halt_slot = None
        for i, d in enumerate(ds):
            if d not in hol:
                continue
            hm = int(halt_of[d])
            hs = (hm - OFF[geom]) % 1440 if geom == "GLOBEX" else hm - 570
            halt_slot = hs
            tradeable[i, hs:] = False
        np.savez_compressed(os.path.join(CACHE, f"tradeable_{root}_{geom}.npz"),
                            tradeable=tradeable, dates=ds, is_holiday=is_hol)
        excl[(root, geom)] = tradeable
        exc_rows.append(dict(root=root, geom=geom, n_sessions=len(ds),
            n_holiday_sessions=int(is_hol.sum()),
            n_minutes_excluded=int((~tradeable).sum()),
            share_minutes_excluded=float((~tradeable).mean()),
            halt_slot=int(halt_slot) if halt_slot is not None else -1))
    pd.DataFrame(exc_rows).to_csv(os.path.join(RES, "phase3_exclusion_counts.csv"), index=False)

    # cross-check against S05B zero-RV windows
    cross = []
    for (root, geom) in [("ES","GLOBEX"),("NQ","GLOBEX"),("ES","RTH"),("NQ","RTH")]:
        dates, grids, present = PANELS[(root, geom)]
        tr = excl[(root, geom)]
        cl = grids["close"]; r1 = np.diff(cl, axis=1)
        trr = tr[:, 1:] & tr[:, :-1]
        for hname, wl in [("1h",60), ("30min",30)]:
            nw = r1.shape[1]//wl
            rw = r1[:, :nw*wl].reshape(-1, wl)
            tw = trr[:, :nw*wl].reshape(-1, wl)
            rv = (rw**2).sum(axis=1)
            excluded = ~tw.any(axis=1)
            zero = rv == 0
            cross.append(dict(root=root, geom=geom, horizon=hname,
                n_windows=int(len(rv)), n_zero_rv=int(zero.sum()),
                n_excluded=int(excluded.sum()),
                n_zero_not_covered=int((zero & ~excluded).sum()),
                n_excluded_with_nonzero_rv=int((excluded & ~zero).sum())))
    CR = pd.DataFrame(cross)
    CR.to_csv(os.path.join(RES, "phase3_crosscheck.csv"), index=False)
    out["phase3_zero_not_covered_total"] = int(CR.n_zero_not_covered.sum())
    out["phase3_excluded_nonzero_total"] = int(CR.n_excluded_with_nonzero_rv.sum())
    timers["phase3"] = round(time.time()-t, 1)

    timers["total"] = round(time.time()-t0, 1)
    out["timers"] = timers
    json.dump(out, open(os.path.join(RES, "phase23_summary.json"), "w"), indent=1, default=str)
    print(json.dumps(out, indent=1, default=str))
    print("\nclose-grid check:\n", pd.DataFrame(cmp_rows).to_string(index=False))
    print("\nM6 old vs new:\n", pd.DataFrame(m6_rows).to_string(index=False))
    print("\ncross-check:\n", CR.to_string(index=False))

if __name__ == "__main__":
    main()
